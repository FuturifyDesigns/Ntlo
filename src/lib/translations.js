export function getTranslation(lang, key, vars = {}) {
  const keys = key.split('.')
  let value = translations[lang]
  for (const k of keys) {
    value = value?.[k]
  }
  if (typeof value !== 'string') return key
  return value.replace(/\{(\w+)\}/g, (_, v) => vars[v] ?? '')
}
